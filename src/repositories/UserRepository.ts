
import pool from "../database.js";
import { User } from "../models/User.js";
import bcrypt from "bcrypt";

interface UserRow {
    user_id: number;
    username: string;
    email: string;
}

export class UserRepository {

    public async findById(userId: number): Promise<User | null> {
        const rows: UserRow[] = await pool.query(
            "SELECT user_id, username, email FROM Users WHERE user_id = ?",
            [userId]
        );

        if (rows.length === 0) {
            return null;
        }

        const row = rows[0]!;

        return new User(row.user_id, row.username, row.email);
    }

    public async findAll(): Promise<User[]> {
        const rows: UserRow[] = await pool.query(
            "SELECT user_id, username, email FROM Users"
        );

        return rows.map(
            (row) => new User(row.user_id, row.username, row.email)
        );
    }


public async login(
    email: string,
    password: string
): Promise<User | null> {

    // Find the user by email
    const rows = await pool.query(
        "SELECT user_id, username, email, password_hash FROM Users WHERE email = ?",
        [email]
    );

    // Return null if the email does not exist
    if (rows.length === 0) {
        return null;
    }

    const row = rows[0];

    // Compare the entered password with the stored hash
    const passwordMatches = await bcrypt.compare(
        password,
        row.password_hash
    );

    if (!passwordMatches) {
        return null;
    }

    // Return the user if the credentials are correct
    return new User(row.user_id, row.username, row.email);
}


public async createUser(
    username: string,
    email: string,
    password: string
): Promise<User> {

    // Hash the password before saving it
    const passwordHash = await bcrypt.hash(password, 12);

    // Insert the new user into MariaDB
    const result = await pool.query(
        "INSERT INTO Users (username, email, password_hash) VALUES (?, ?, ?)",
        [username, email, passwordHash]
    );

    // Retrieve the ID generated by MariaDB
    const userId = Number(result.insertId);

    return new User(userId, username, email);
}

}
